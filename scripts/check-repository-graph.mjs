async function checkCommitActions(app, page, cwd, linked, graph, sidebar) {
  await git.git(cwd, ['switch', 'main'])
  const head = (await git.git(cwd, ['rev-parse', 'HEAD'])).trim()
  await writeFile(path.join(linked, 'backport.txt'), 'selected change\n')
  await git.git(linked, ['add', 'backport.txt'])
  await git.git(linked, ['commit', '-m', '백포트할 수정'])
  const source = (await git.git(linked, ['rev-parse', 'HEAD'])).trim()
  await git.git(linked, ['commit', '--allow-empty', '-m', '후속 작업'])
  const refresh = page.getByRole('button', { name: '상태 새로고침', exact: true })
  await refresh.click()
  await sidebar.getByRole('button', { name: '전체 브랜치 그래프', exact: true }).click()
  const headRow = graph.locator(`.bl-graph-row[data-sha="${head}"]`)
  const sourceRow = graph.locator(`.bl-graph-row[data-sha="${source}"]`)
  await headRow.locator('.bl-graph-title').click()
  const more = graph.getByRole('button', { name: `커밋 ${head.slice(0, 8)} 메뉴`, exact: true })
  await more.click()
  const pick = { name: '현재 브랜치로 Cherry-pick…', exact: true }
  assert.equal(await page.getByRole('menuitem', pick).isDisabled(), true)
  await page.keyboard.press('Escape')
  await sourceRow.locator('.bl-graph-title').click({ button: 'right' })
  const menu = page.getByRole('menu', { name: `커밋 ${source.slice(0, 8)}`, exact: true })
  await menu.getByRole('menuitem', { name: '전체 SHA 복사' }).click()
  await page.getByText('커밋 SHA를 복사했습니다.', { exact: true }).waitFor()
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.historyTestValue), source)
  assert.equal(await headRow.getAttribute('aria-pressed'), 'true')
  assert.equal(await sourceRow.getAttribute('aria-pressed'), 'false')

  await sourceRow.focus()
  const scrollTop = await graph.evaluate(el => el.scrollTop)
  await sourceRow.press('Shift+F10')
  await menu.getByRole('menuitem', pick).press('Enter')
  const review = page.getByRole('dialog', { name: 'Cherry-pick 검토' })
  await review.getByText(/현재 main/).waitFor()
  assert.ok((await review.innerText()).includes(source.slice(0, 8)))
  assert.equal(await review.locator(`pre[title="${source}"]`).count(), 1, "Full SHA stays available on the short label")
  await page.keyboard.press('Escape')
  await review.waitFor({ state: 'hidden' })
  await sourceRow.and(page.locator(':focus')).waitFor()
  assert.equal(await graph.evaluate(el => el.scrollTop), scrollTop)
  assert.equal((await git.git(cwd, ['rev-parse', 'HEAD'])).trim(), head)

  await sourceRow.press('Shift+F10')
  await menu.getByRole('menuitem', { name: '이 커밋에서 브랜치 만들기…' }).click()
  const branch = page.getByRole('dialog', { name: '브랜치 만들기' })
  await branch.getByLabel('새 브랜치 이름').fill('review/backport')
  await branch.getByLabel('새 브랜치 이름').press('Enter')
  await branch.waitFor({ state: 'hidden' })
  assert.equal((await git.git(cwd, ['rev-parse', 'review/backport'])).trim(), source)
  assert.equal((await git.git(cwd, ['branch', '--show-current'])).trim(), 'main')

  const dirty = path.join(cwd, 'local-draft.txt')
  await writeFile(dirty, 'unsaved change')
  await refresh.click()
  await page.getByRole('button', { name: '내 변경 사항 1', exact: true }).waitFor()
  await sourceRow.press('Shift+F10')
  assert.equal(await menu.getByRole('menuitem', pick).isDisabled(), true)
  assert.match(await menu.getByRole('menuitem', pick).getAttribute('aria-description'), /Stash/)
  await page.keyboard.press('Escape')
  await unlink(dirty)
  await refresh.click()
  await page.getByRole('button', { name: '내 변경 사항 0', exact: true }).waitFor()
  await sourceRow.press('Shift+F10')
  await menu.getByRole('menuitem', pick).click()
  await review.getByRole('button', { name: 'Cherry-pick 실행', exact: true }).click()
  await review.waitFor({ state: 'hidden' })
  assert.equal(await git.git(cwd, ['show', 'HEAD:backport.txt']), 'selected change\n')
  assert.equal((await git.git(cwd, ['rev-parse', 'HEAD^'])).trim(), head)
  assert.ok((await git.git(cwd, ['log', '-1', '--format=%B'])).includes(source))
  console.log('PASS: history row copy, branch without checkout, Cherry-pick of the targeted non-tip SHA, dirty and HEAD guards, cancel focus and scroll')
}
