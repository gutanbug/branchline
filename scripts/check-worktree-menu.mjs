import assert from 'node:assert/strict'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import path from 'node:path'
import git from '../electron/git.cjs'

export async function checkWorktreeMenu(app, page, root, accessibility) {
  const cwd = path.join(root, 'worktree-menu'), target = path.join(root, 'menu-linked')
  await mkdir(cwd)
  await git.git(cwd, ['init', '-b', 'main'])
  await git.git(cwd, ['config', 'user.name', 'Worktree Test']); await git.git(cwd, ['config', 'user.email', 'worktree@example.invalid'])
  await writeFile(path.join(cwd, 'file.txt'), 'base\n')
  await git.git(cwd, ['add', '.']); await git.git(cwd, ['-c', 'commit.gpgsign=false', 'commit', '-m', 'base'])
  await git.git(cwd, ['worktree', 'add', '-b', 'topic', target])
  const head = (await git.state(cwd)).head
  await app.evaluate(({ dialog }, cwd) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [cwd] }) }, cwd)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('button', { name: '저장소 추가', exact: true }).click(); await page.getByRole('menuitem', { name: '저장소 열기', exact: true }).click()
  const sidebar = page.getByRole('region', { name: '현재 저장소 탐색' }), tabs = page.locator('.bl-project-tab')
  const linked = sidebar.getByRole('button', { name: `Worktree 열기: topic · ${target}`, exact: true })
  const main = sidebar.getByRole('button', { name: `Worktree 열기: main · ${cwd}`, exact: true })
  await linked.waitFor()
  const count = await tabs.count()
  async function menu(item, name, keyboard = false) {
    if (keyboard) { await item.focus(); await page.keyboard.press('Shift+F10') } else await item.click({ button: 'right' })
    const popup = page.getByRole('menu', { name: `Worktree · ${name}`, exact: true }); await popup.waitFor(); return popup
  }
  let popup = await menu(linked, 'topic', true)
  await page.setViewportSize({ width: 760, height: 580 })
  await accessibility(page)
  const box = await popup.boundingBox(); assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= 760 && box.y + box.height <= 580)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'worktree-menu-narrow.png') })
  await page.keyboard.press('Escape'); await popup.waitFor({ state: 'hidden' })
  assert.equal(await linked.evaluate(node => document.activeElement === node), true)
  await page.setViewportSize({ width: 1440, height: 950 })
  popup = await menu(linked, 'topic'); await popup.getByRole('menuitem', { name: 'Worktree 잠금', exact: true }).click()
  await page.waitForFunction(target => [...document.querySelectorAll('.bl-repo-tree-item')].some(node => node.getAttribute('aria-label')?.endsWith(target) && node.title.startsWith('잠김')), target)
  assert.equal((await git.worktrees(cwd)).find(w => w.path === target).locked, true)
  popup = await menu(linked, 'topic')
  assert.equal(await popup.getByRole('menuitem', { name: 'Worktree 제거…' }).getAttribute('aria-disabled'), 'true')
  await popup.getByRole('menuitem', { name: 'Worktree 잠금 해제', exact: true }).click()
  await page.waitForFunction(target => [...document.querySelectorAll('.bl-repo-tree-item')].some(node => node.getAttribute('aria-label')?.endsWith(target) && !node.title.startsWith('잠김')), target)
  popup = await menu(linked, 'topic'); await popup.getByRole('menuitem', { name: '새 탭에서 열기', exact: true }).click()
  await page.getByRole('button', { name: 'menu-linked 탭 닫기', exact: true }).waitFor()
  assert.equal(await tabs.count(), count + 1)
  popup = await menu(linked, 'topic'); assert.equal(await popup.getByRole('menuitem', { name: 'Worktree 제거…' }).getAttribute('aria-disabled'), 'true'); await page.keyboard.press('Escape')
  popup = await menu(main, 'main'); await popup.getByRole('menuitem', { name: '현재 탭에서 열기' }).click()
  await page.getByRole('button', { name: 'menu-linked 탭 닫기', exact: true }).waitFor({ state: 'hidden' }); assert.equal(await tabs.count(), count)
  // Replace an unopened target in-place and restore this repository's commit draft.
  await page.getByRole('button', { name: '내 변경 사항 0', exact: true }).click()
  await page.getByRole('textbox', { name: '커밋 메시지', exact: true }).fill('전환 뒤에도 남는 커밋 초안')
  popup = await menu(linked, 'topic'); await popup.getByRole('menuitem', { name: '현재 탭에서 열기' }).click()
  await page.getByRole('button', { name: 'worktree-menu 탭 닫기', exact: true }).waitFor({ state: 'hidden' }); assert.equal(await tabs.count(), count)
  popup = await menu(main, 'main'); await popup.getByRole('menuitem', { name: '현재 탭에서 열기' }).click()
  await page.getByRole('button', { name: 'worktree-menu 탭 닫기', exact: true }).waitFor()
  await page.getByRole('button', { name: '내 변경 사항 0', exact: true }).click()
  assert.equal(await page.getByRole('textbox', { name: '커밋 메시지', exact: true }).inputValue(), '전환 뒤에도 남는 커밋 초안')
  await page.getByRole('button', { name: '폴더에서 보기', exact: true }).click()
  await page.getByRole('button', { name: 'file.txt 파일 열기', exact: true }).click()
  const editor = page.getByRole('textbox', { name: '파일 내용', exact: true }); await editor.fill('저장 전 초안')
  popup = await menu(linked, 'topic'); await popup.getByRole('menuitem', { name: '현재 탭에서 열기' }).click()
  await page.getByRole('alert').filter({ hasText: '현재 탭의 편집을 저장하거나' }).waitFor()
  assert.equal(await editor.inputValue(), '저장 전 초안'); assert.equal(await readFile(path.join(cwd, 'file.txt'), 'utf8'), 'base\n')
  await editor.fill('base\n'); await page.getByRole('button', { name: '작업 폴더 탭 닫기', exact: true }).click()
  popup = await menu(linked, 'topic'); await popup.getByRole('menuitem', { name: 'Worktree와 브랜치 제거…' }).click()
  let dialog = page.getByRole('dialog', { name: 'Worktree와 브랜치 제거', exact: true })
  assert.ok((await dialog.innerText()).includes(target)); assert.ok((await dialog.innerText()).includes('topic'))
  await dialog.getByRole('button', { name: '취소', exact: true }).click(); assert.equal((await git.worktrees(cwd)).length, 2)
  // Ordinary removal leaves the branch intact.
  popup = await menu(linked, 'topic'); await popup.getByRole('menuitem', { name: 'Worktree 제거…', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Worktree 삭제', exact: true })
  await dialog.getByRole('button', { name: 'Worktree 삭제', exact: true }).click(); await linked.waitFor({ state: 'hidden' })
  assert.equal((await git.state(cwd)).refs.some(ref => ref.ref === 'refs/heads/topic'), true)
  await git.git(cwd, ['worktree', 'add', target, 'topic']); await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  popup = await menu(linked, 'topic'); await popup.getByRole('menuitem', { name: 'Worktree와 브랜치 제거…' }).click()
  dialog = page.getByRole('dialog', { name: 'Worktree와 브랜치 제거', exact: true })
  await dialog.getByRole('button', { name: 'Worktree와 브랜치 제거', exact: true }).click(); await linked.waitFor({ state: 'hidden' })
  assert.equal((await git.state(cwd)).refs.some(ref => ref.ref === 'refs/heads/topic'), false)
  assert.equal((await git.state(cwd)).head, head)
  await page.getByRole('button', { name: 'worktree-menu 탭 닫기', exact: true }).click()
  console.log('PASS: Worktree context menu, lock/unlock, new/current tab and deduplication, draft protection, ordinary/combined removal, cancellation, keyboard and narrow accessibility')
}
