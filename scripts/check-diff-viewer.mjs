import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import git from '../electron/git.cjs'

export async function checkDiffViewer(app, page, root, accessibility) {
  const cwd = path.join(root, 'diff-viewer')
  await mkdir(cwd)
  await git.git(cwd, ['init', '-b', 'main'])
  for (const [name, value] of [['user.name', 'Diff Test'], ['user.email', 'diff@example.invalid'], ['commit.gpgsign', 'false']]) await git.git(cwd, ['config', name, value])
  const lines = Array.from({ length: 80 }, (_, index) => `line ${index + 1}: 개발 환경 설정`)
  await writeFile(path.join(cwd, 'config.yml'), lines.join('\n') + '\n')
  await git.git(cwd, ['add', '.']); await git.git(cwd, ['commit', '-m', '기준 설정'])
  lines.splice(2, 1, 'enabled: true', `endpoint: https://example.invalid/${'very-long-path/'.repeat(20)}`)
  lines[65] = 'image: updated'
  await writeFile(path.join(cwd, 'config.yml'), lines.join('\n'))
  await writeFile(path.join(cwd, '새 파일.txt'), '새로운 파일 내용\n')
  await mkdir(path.join(cwd, 'src', '한글'), { recursive: true }); await writeFile(path.join(cwd, 'src', '한글', 'config.yml'), 'nested: true\n')
  await git.git(cwd, ['add', '.']); await git.git(cwd, ['commit', '-m', '설정 변경 검토'])
  for (let i = 0; i < 24; i++) await git.git(cwd, ['commit', '--allow-empty', '-m', `후속 이력 ${i}`])
  await writeFile(path.join(cwd, '초안.txt'), '+ 원문\n- 원문\n' + '내용\n'.repeat(300))
  const before = await git.state(cwd)
  await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }) }, cwd)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('button', { name: '저장소 열기', exact: true }).first().click()
  await page.locator('.bl-graph-row').filter({ hasText: '설정 변경 검토' }).click()
  const inspector = page.getByRole('complementary', { name: '커밋 상세', exact: true })
  await inspector.getByRole('region', { name: '변경 파일 목록' }).waitFor()
  assert.equal(await inspector.locator('.bl-diff-viewer').count(), 0, 'Commit detail lists files without inline code')
  const graph = page.locator('.bl-commit-graph:visible')
  const scroll = await graph.evaluate(element => element.scrollTop)
  assert.ok(scroll > 0, 'Fixture exercises graph scroll restoration')
  await inspector.getByRole('button', { name: '커밋 상세 크게 보기' }).click()
  const expanded = page.getByRole('dialog', { name: '커밋 상세 크게 보기' })
  await expanded.getByRole('button', { name: '트리', exact: true }).click()
  await expanded.getByText('한글', { exact: true }).focus(); await page.keyboard.press('Enter')
  assert.equal(await expanded.getByRole('button', { name: 'src/한글/config.yml 변경 열기' }).isVisible(), false)
  await page.keyboard.press('Enter')
  await expanded.getByRole('button', { name: 'src/한글/config.yml 변경 열기' }).click()
  await expanded.getByText('nested: true', { exact: true }).waitFor()
  assert.equal(await page.getByRole('tab', { name: 'src/한글/config.yml', exact: true }).count(), 0, 'Expanded file opens inside the modal')
  await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'expanded-file-diff.png') })
  await page.setViewportSize({ width: 760, height: 580 }); await accessibility(page)
  assert.ok(await expanded.getByRole('region', { name: '통합 diff 코드' }).evaluate(el => el.clientHeight >= 60))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'expanded-file-narrow.png') })
  await expanded.getByRole('button', { name: '← 변경 파일 목록' }).click()
  assert.equal(await expanded.getByRole('button', { name: '트리', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.equal(await expanded.getByRole('button', { name: 'src/한글/config.yml 변경 열기' }).evaluate(el => el === document.activeElement), true)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'expanded-file-tree.png') })
  await expanded.getByRole('button', { name: 'config.yml 변경 열기', exact: true }).click()
  await expanded.getByText('enabled: true', { exact: true }).waitFor()
  await page.keyboard.press('Escape'); await expanded.waitFor({ state: 'hidden' })
  assert.equal(await inspector.isVisible(), true, 'Closing the expanded modal preserves the selected commit')
  await page.setViewportSize({ width: 1440, height: 950 })
  await inspector.getByRole('button', { name: 'config.yml 변경 열기', exact: true }).click()
  const file = page.getByRole('tabpanel', { name: 'config.yml', exact: true })
  await file.getByText('enabled: true', { exact: true }).waitFor()
  assert.equal(await page.locator('.bl-commit-graph:visible').count(), 0)
  assert.equal(await file.getByLabel('이전 3행', { exact: true }).textContent(), '3')
  assert.equal(await file.getByLabel('이후 4행', { exact: true }).textContent(), '4')
  await inspector.getByRole('button', { name: '새 파일.txt 변경 열기' }).click()
  await page.getByRole('tabpanel', { name: '새 파일.txt', exact: true }).getByText('새로운 파일 내용', { exact: true }).waitFor()
  await inspector.getByRole('button', { name: 'config.yml 변경 열기', exact: true }).click()
  assert.equal(await page.getByRole('tab', { name: 'config.yml', exact: true }).count(), 1, 'Reopening does not duplicate tabs')
  await file.getByRole('button', { name: '좌우 비교', exact: true }).click()
  assert.ok(await file.locator('.bl-diff-gap').count() > 0)
  const viewport = file.getByRole('region', { name: '좌우 diff 코드' })
  assert.ok(await viewport.evaluate(element => element.scrollWidth > element.clientWidth), 'Long code scrolls inside the viewer')
  await file.getByRole('button', { name: '다음 변경 구간' }).click()
  await file.getByRole('button', { name: '다음 변경 구간' }).click()
  assert.equal(await file.locator('[data-hunk="1"]').evaluate(element => document.activeElement === element), true)
  await file.getByRole('button', { name: '이전 변경 구간' }).click()
  await file.getByRole('checkbox', { name: '줄바꿈' }).check()
  await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'file-tab-split.png') })
  await file.getByRole('button', { name: '통합 보기', exact: true }).click()
  await file.getByRole('button', { name: '원본 diff' }).click()
  await file.getByText('+++ b/config.yml', { exact: true }).waitFor()
  await file.getByRole('button', { name: '통합 보기', exact: true }).click()
  await page.getByRole('tab', { name: '그래프', exact: true }).click()
  await page.waitForFunction(expected => document.querySelector('.bl-repository:not([hidden]) .bl-content-tabpanel:not([hidden]) .bl-commit-graph')?.scrollTop === expected, scroll)
  assert.equal(await graph.evaluate(element => element.scrollTop), scroll, 'Graph position survives switching tabs')
  await page.getByRole('tab', { name: 'config.yml', exact: true }).click()
  assert.equal(await file.getByRole('checkbox', { name: '줄바꿈' }).isChecked(), true)
  await page.setViewportSize({ width: 760, height: 580 })
  await accessibility(page)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.ok(await file.getByRole('region', { name: '통합 diff 코드' }).evaluate(el => el.clientHeight > 60 && el.scrollWidth <= el.clientWidth + 1))
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'file-tab-narrow.png') })
  await file.getByRole('region', { name: '통합 diff 코드' }).focus()
  await file.evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, isComposing: true })))
  assert.equal(await file.isVisible(), true, 'IME Escape must not close the file')
  await page.keyboard.press('Escape')
  await file.waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('tab', { name: 'config.yml', exact: true }).count(), 0)
  assert.equal(await inspector.isVisible(), true, 'Escape closes only the file tab, preserving commit selection')
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('tab', { name: '새 파일.txt', exact: true }).click()
  await page.getByRole('button', { name: '새 파일.txt 탭 닫기', exact: true }).click()
  await page.getByRole('tab', { name: '그래프', exact: true }).waitFor()
  await page.waitForFunction(expected => document.querySelector('.bl-repository:not([hidden]) .bl-content-tabpanel:not([hidden]) .bl-commit-graph')?.scrollTop === expected, scroll)
  assert.equal(await graph.evaluate(element => element.scrollTop), scroll)
  await inspector.getByRole('button', { name: 'config.yml 변경 열기', exact: true }).click()
  await page.getByRole('tab', { name: '그래프', exact: true }).click()
  await graph.getByRole('button', { name: /후속 이력 23/ }).click()
  await page.getByRole('region', { name: '변경 파일 목록' }).getByText('변경 파일이 없습니다', { exact: true }).waitFor()
  assert.equal(await page.getByRole('tab', { name: 'config.yml', exact: true }).count(), 0, 'A different commit clears previous file tabs')
  await page.getByRole('button', { name: /^내 변경 사항/ }).click()
  await page.locator('.bl-change-file').filter({ hasText: '초안.txt' }).click()
  const draft = page.getByRole('complementary', { name: '초안.txt', exact: true })
  await draft.getByText('+ 원문', { exact: true }).waitFor()
  assert.equal(await draft.getByRole('button', { name: '좌우 비교', exact: true }).count(), 1)
  assert.ok(await draft.locator('.bl-diff-add').count() > 100, 'new file lines use the shared addition style')
  assert.ok(await draft.getByRole('region', { name: '통합 diff 코드' }).evaluate(el => el.scrollHeight > el.clientHeight && el.clientHeight > 60))
  await accessibility(page)
  const after = await git.state(cwd)
  assert.equal(after.head, before.head); assert.deepEqual(after.files, before.files)
  console.log('PASS: real Git unified/split/raw diff, line numbers, unequal gaps, file selection, hunk navigation, horizontal scroll, wrapping, minimum window, accessibility and read-only state')
}
