  assert.equal(await readFile(path.join(repo, 'draft.txt'), 'utf8'), 'keep my draft\n')
  assert.equal((await run(['stash', 'list'])).trim(), '')
  console.log('PASS: non-fast-forward Push opens the exact ref comparison or fast-forward Pull, preserving draft and remote tip')
