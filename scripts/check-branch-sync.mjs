  const comparison = page.getByRole('region', { name: '브랜치 비교 작업' })
  assert.equal(await comparison.getByRole('combobox', { name: '가져올 브랜치', exact: true }).inputValue(), 'refs/remotes/team/server-topic')
  assert.equal(await comparison.getByRole('combobox', { name: '반영할 브랜치', exact: true }).inputValue(), 'refs/heads/topic')
  assert.equal((await run(['rev-parse', 'HEAD'])).trim(), local)
