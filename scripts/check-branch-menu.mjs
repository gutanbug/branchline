import assert from 'node:assert/strict'
import { mkdir, writeFile, readFile, unlink } from 'node:fs/promises'
import path from 'node:path'
import git from '../electron/git.cjs'

export async function checkBranchMenu(app, page, root, accessibility) {
  const cwd = path.join(root, 'branch-menu-project')
  await mkdir(cwd); await git.git(cwd, ['init', '-b', 'main'])
  await git.git(cwd, ['config', 'user.name', 'Branch Review']); await git.git(cwd, ['config', 'user.email', 'review@example.invalid']); await git.git(cwd, ['config', 'commit.gpgsign', 'false'])
  await writeFile(path.join(cwd, 'review.txt'), 'base\n'); await git.git(cwd, ['add', '.']); await git.git(cwd, ['commit', '-m', '기준: 배포된 변경'])
  const base = (await git.state(cwd)).head
  await git.git(cwd, ['branch', 'release/stable'])
  await git.git(cwd, ['switch', '-c', 'feature/review'])
  await writeFile(path.join(cwd, 'review.txt'), 'base\nreview\n'); await git.git(cwd, ['commit', '-am', '기능: 검토할 브랜치 변경'])
  const feature = (await git.state(cwd)).head
  await git.git(cwd, ['switch', 'main'])
  for (let i = 0; i < 108; i++) await git.git(cwd, ['commit', '--allow-empty', '-m', `현재 브랜치 이력 ${i}`])
  await git.git(cwd, ['remote', 'add', 'origin', path.join(root, 'offline.git')])
  await git.git(cwd, ['remote', 'add', 'empty', path.join(root, 'empty-offline.git')])
  await git.git(cwd, ['update-ref', 'refs/remotes/origin/review', feature])
  await app.evaluate(({ dialog, clipboard }, cwd) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [cwd] }); clipboard.writeText = value => { clipboard.branchMenuValue = value } }, cwd)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('button', { name: '저장소 추가', exact: true }).click(); await page.getByRole('menuitem', { name: '저장소 열기', exact: true }).click()
  await page.getByRole('button', { name: /^branch-menu-project main/ }).waitFor()
  const sidebar = page.getByRole('region', { name: '현재 저장소 탐색' }), graph = page.locator('.bl-commit-graph:visible')
  const branch = name => sidebar.getByRole('button', { name: `이력 조회: ${name}`, exact: true })
  const menu = page.getByRole('menu')
  const open = async name => { await sidebar.getByRole('button', { name: 'LOCAL 전체 펼치기', exact: true }).click(); await branch(name).click({ button: 'right' }); await menu.waitFor() }
  const choose = async name => page.getByRole('menuitem', { name, exact: true }).click()
  // Selecting an old branch loads through its tip, without Solo or checkout.
  await sidebar.getByRole('button', { name: 'LOCAL 전체 펼치기', exact: true }).click()
  await sidebar.getByText('원격 추적 브랜치가 없습니다.', { exact: false }).waitFor()
  await sidebar.getByLabel('브랜치·Stash·Worktree 찾기').fill('main')
  await sidebar.getByRole('button', { name: '브랜치 검색 지우기' }).click()
  assert.equal(await branch('feature/review').isVisible(), true)
  await branch('release/stable').click()
  await page.getByRole('complementary', { name: '커밋 상세', exact: true }).locator(`code[title="${base}"]`).waitFor()
  await graph.locator(`svg[data-sha="${base}"]`).waitFor()
  assert.ok(Number(await graph.getAttribute('data-commit-count')) > 100)
  assert.equal((await git.state(cwd)).branch, 'main')
  assert.match(await page.locator('.bl-graph-context:visible').innerText(), /전체 브랜치/)
  const node = await graph.locator(`svg[data-sha="${base}"]`).boundingBox(), box = await graph.boundingBox()
  assert.ok(node.y >= box.y && node.y < box.y + box.height)
  // Overflow badges show actual refs without changing selection or checkout.
  const overflow = graph.locator('.bl-graph-ref-overflow:visible').first()
  const selectedBeforeHover = await graph.locator('.bl-graph-row[aria-pressed=true] svg').getAttribute('data-sha')
  await overflow.hover()
  const tooltip = page.getByRole('tooltip')
  await tooltip.getByText('연결된 브랜치 2개', { exact: true }).waitFor()
  await tooltip.getByText('feature/review', { exact: true }).waitFor()
  await tooltip.getByText('origin/review', { exact: true }).waitFor()
  await tooltip.hover(); await accessibility(page)
  const tooltipBox = await tooltip.boundingBox()
  assert.ok(tooltipBox.x >= 0 && tooltipBox.x + tooltipBox.width <= 1440)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'branch-overflow-tooltip.png') })
  await page.keyboard.press('Escape'); await tooltip.waitFor({ state: 'hidden' })
  assert.equal(await graph.locator('.bl-graph-row[aria-pressed=true] svg').getAttribute('data-sha'), selectedBeforeHover)
  assert.equal((await git.state(cwd)).branch, 'main')
  await overflow.locator('xpath=ancestor::button[1]').focus()
  await tooltip.waitFor()
  await page.keyboard.press('Escape'); await tooltip.waitFor({ state: 'hidden' })
  assert.equal(await graph.locator('.bl-graph-row[aria-pressed=true] svg').getAttribute('data-sha'), selectedBeforeHover, 'Tooltip Escape must not clear commit selection')
  // Node tooltips follow actual ancestry, including commits without a ref badge.
  const oldRow = graph.getByRole('button', { name: /현재 브랜치 이력 0 / })
  await oldRow.focus(); await oldRow.locator('.bl-graph-node-trigger').hover()
  await tooltip.getByText('main', { exact: true }).waitFor()
  assert.equal(await tooltip.getByText('feature/review', { exact: true }).count(), 0)
  await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'commit-node-branches.png') })
  await page.keyboard.press('Escape'); await tooltip.waitFor({ state: 'hidden' })
  assert.equal(await graph.locator('.bl-graph-row[aria-pressed=true] svg').getAttribute('data-sha'), selectedBeforeHover)
  const baseRow = graph.locator(`svg[data-sha="${base}"]`).locator('xpath=ancestor::button[1]')
  await baseRow.focus(); await baseRow.locator('.bl-graph-node-trigger').hover()
  for (const name of ['main', 'release/stable', 'feature/review', 'origin/review']) await tooltip.getByText(name, { exact: true }).waitFor()
  await page.keyboard.press('Escape'); await tooltip.waitFor({ state: 'hidden' })
  assert.equal((await git.state(cwd)).branch, 'main')
  // Explicit Solo preserves inspection but changes the reachable set.
  await open('feature/review'); await choose('Solo · 이 브랜치만 보기')
  await page.waitForFunction(() => document.querySelector('.bl-repository:not([hidden]) .bl-commit-graph')?.querySelectorAll('.bl-graph-row').length === 2)
  assert.match(await page.locator('.bl-graph-context:visible').innerText(), /Solo · feature\/review/)
  await page.getByRole('button', { name: 'Solo 해제', exact: true }).click()
  await graph.getByRole('button', { name: /현재 브랜치 이력 107/ }).waitFor()
  await sidebar.getByRole('button', { name: 'LOCAL 전체 펼치기', exact: true }).click()
  await branch('feature/review').focus(); await page.keyboard.press('Shift+F10'); await menu.waitFor()
  await page.keyboard.press('Escape'); await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '이력 조회: feature/review')
  await sidebar.getByRole('button', { name: 'feature/review 메뉴', exact: true }).click(); await menu.waitFor()
  await choose('브랜치 이름 복사'); await page.getByText('브랜치 이름을 복사했습니다.', { exact: true }).waitFor(); assert.equal(await app.evaluate(({ clipboard }) => clipboard.branchMenuValue), 'feature/review')
  await open('feature/review'); await choose('커밋 SHA 복사'); await page.getByText('커밋 SHA를 복사했습니다.', { exact: true }).waitFor(); assert.equal(await app.evaluate(({ clipboard }) => clipboard.branchMenuValue), feature)
  await open('feature/review'); await choose('현재 브랜치와 비교')
  assert.equal(await page.getByRole('combobox', { name: '가져올 브랜치', exact: true }).inputValue(), 'refs/heads/feature/review')
  assert.equal(await page.getByRole('combobox', { name: '반영할 브랜치', exact: true }).inputValue(), 'refs/heads/main')
  await branch('feature/review').click()
  // Ref badge shares the menu without selecting the graph row on menu-item clicks.
  const badge = graph.locator('.bl-graph-refs .bl-graph-ref-name').filter({ hasText: 'feature/review' }).first()
  await badge.click({ button: 'right' }); await menu.waitFor(); await choose('커밋 SHA 복사')
  assert.equal(await page.getByRole('complementary', { name: '커밋 상세', exact: true }).count(), 1)
  await open('feature/review'); await choose('여기서 브랜치 만들기…')
  let dialog = page.getByRole('dialog', { name: '브랜치 만들기', exact: true })
  assert.match(await dialog.innerText(), new RegExp(feature.slice(0, 12)))
  await dialog.getByLabel('새 브랜치 이름', { exact: true }).fill('review/한글')
  await dialog.getByRole('button', { name: '브랜치만 만들기', exact: true }).click(); await dialog.waitFor({ state: 'hidden' })
  assert.equal((await git.git(cwd, ['rev-parse', 'review/한글'])).trim(), feature)
  await open('review/한글'); await choose('브랜치 이름 변경…')
  dialog = page.getByRole('dialog', { name: '브랜치 이름 변경', exact: true })
  await dialog.getByLabel('새 브랜치 이름', { exact: true }).fill('review/변경')
  await dialog.getByRole('button', { name: '저장', exact: true }).click(); await dialog.waitFor({ state: 'hidden' })
  await sidebar.getByRole('button', { name: 'LOCAL 전체 펼치기', exact: true }).click()
  await branch('review/변경').waitFor()
  await open('review/변경'); await choose('로컬 브랜치 삭제…')
  dialog = page.getByRole('dialog', { name: '로컬 브랜치 삭제', exact: true })
  await dialog.getByRole('button', { name: '로컬 브랜치 삭제', exact: true }).click()
  await dialog.getByRole('alert').filter({ hasText: '병합되지' }).waitFor()
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  await open('release/stable'); await choose('로컬 브랜치 삭제…')
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  assert.ok((await git.state(cwd)).refs.some(r => r.ref === 'refs/heads/release/stable'))
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '이력 조회: release/stable')
  await open('release/stable'); await choose('로컬 브랜치 삭제…')
  await dialog.getByRole('button', { name: '로컬 브랜치 삭제', exact: true }).click(); await dialog.waitFor({ state: 'hidden' })
  await writeFile(path.join(cwd, 'carry.txt'), '미추적 작업\n')
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await open('origin/review'); await choose('로컬 추적 브랜치로 체크아웃…')
  dialog = page.getByRole('dialog', { name: '로컬 추적 브랜치 체크아웃', exact: true })
  await dialog.getByLabel('새 브랜치 이름', { exact: true }).fill('local/review')
  await dialog.getByRole('button', { name: '저장', exact: true }).click(); await dialog.waitFor({ state: 'hidden' })
  assert.equal((await git.state(cwd)).branch, 'local/review')
  assert.equal(await readFile(path.join(cwd, 'carry.txt'), 'utf8'), '미추적 작업\n')
  assert.equal((await git.git(cwd, ['stash', 'list'])).trim(), '')
  await unlink(path.join(cwd, 'carry.txt'))
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  assert.equal((await git.git(cwd, ['rev-parse', '--symbolic-full-name', '@{u}'])).trim(), 'refs/remotes/origin/review')
  await open('main'); await choose('브랜치 체크아웃')
  await page.getByRole('button', { name: /^branch-menu-project main/ }).waitFor()
  await open('origin/review'); await choose('로컬 추적 브랜치로 체크아웃…')
  await page.getByRole('button', { name: /^branch-menu-project local\/review/ }).waitFor()
  assert.equal((await git.state(cwd)).branch, 'local/review')
  const linked = path.join(root, 'tracking-worktree')
  await git.git(cwd, ['branch', '--track', 'alternate', 'refs/remotes/origin/review'])
  await git.git(cwd, ['worktree', 'add', linked, 'alternate'])
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await open('alternate')
  await page.getByRole('menuitem', { name: '브랜치의 Worktree 열기' }).waitFor()
  for (const name of ['브랜치 이름 변경…', '로컬 브랜치 삭제…']) assert.equal(await page.getByRole('menuitem', { name, exact: true }).isDisabled(), true)
  await page.getByRole('menuitem', { name: 'Fetch / Pull' }).hover()
  assert.equal(await page.getByRole('menuitem', { name: 'Pull', exact: true }).isDisabled(), true)
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape')
  await open('origin/review'); await choose('로컬 추적 브랜치로 체크아웃…')
  dialog = page.getByRole('dialog', { name: '추적 브랜치 선택', exact: true })
  await dialog.getByRole('combobox').selectOption('refs/heads/alternate')
  await dialog.getByRole('button', { name: '선택한 브랜치 열기' }).click()
  await page.getByRole('button', { name: /^tracking-worktree alternate/ }).waitFor()
  assert.equal((await git.state(cwd)).branch, 'local/review')
  await page.getByRole('button', { name: 'tracking-worktree 탭 닫기', exact: true }).click()
  await open('main'); await choose('여기서 Worktree 만들기…')
  dialog = page.getByRole('dialog', { name: 'Worktree 만들기', exact: true })
  assert.equal(await dialog.getByLabel('Worktree 시작 커밋 또는 브랜치', { exact: true }).inputValue(), (await git.git(cwd, ['rev-parse', 'main'])).trim())
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  await open('main'); await choose('현재 브랜치에 Merge…')
  dialog = page.getByRole('dialog', { name: 'Merge 검토', exact: true })
  assert.match(await dialog.innerText(), /local\/review/); await dialog.getByRole('button', { name: '취소', exact: true }).click()
  // Screenshots include menu bounds, disabled reasons, and the same actions at minimum size.
  for (const size of [{ width: 1440, height: 950 }, { width: 760, height: 580 }]) {
    await page.setViewportSize(size); await open('main'); await accessibility(page)
    const bounds = await menu.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= size.width && bounds.y + bounds.height <= size.height)
    if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, `branch-menu-${size.width}.png`) })
    await page.keyboard.press('Escape')
  }
  await open('local/review')
  assert.equal(await page.getByRole('menuitem', { name: /^로컬 브랜치 삭제/ }).getAttribute('aria-disabled'), 'true')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1440, height: 950 })
  // Non-overlapping dirty checkout carries staged edits without a stash.
  await writeFile(path.join(cwd, 'carry.txt'), '스테이징 작업\n')
  await git.git(cwd, ['add', 'carry.txt'])
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await open('main'); await choose('브랜치 체크아웃')
  await page.getByText('작업 변경을 유지하며 브랜치를 전환했습니다.', { exact: true }).waitFor()
  assert.equal(await page.getByRole('dialog').count(), 0)
  await page.setViewportSize({ width: 760, height: 580 }); await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'checkout-auto-stash.png') })
  assert.equal((await git.state(cwd)).branch, 'main')
  assert.equal(await git.git(cwd, ['show', ':carry.txt']), '스테이징 작업\n')
  assert.equal((await git.git(cwd, ['stash', 'list'])).trim(), '')
  // A restore conflict rolls back: the user stays on the original branch with the same edits and no leftover stash.
  await git.git(cwd, ['reset', '--hard', 'HEAD'])
  const before = (await git.state(cwd)).branch
  await writeFile(path.join(cwd, 'review.txt'), '내 충돌 변경\n')
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await open('local/review'); await choose('브랜치 체크아웃')
  await page.getByRole('alert').filter({ hasText: '겹쳐 체크아웃하지 않았습니다' }).first().waitFor()
  assert.equal((await git.state(cwd)).branch, before)
  assert.ok(!(await git.state(cwd)).files.some(file => file.conflict))
  assert.equal(await readFile(path.join(cwd, 'review.txt'), 'utf8'), '내 충돌 변경\n')
  assert.equal((await git.git(cwd, ['stash', 'list'])).trim(), '')
  await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'checkout-stash-conflict.png') })
  // Continue the remaining flow from the destination branch as before.
  await git.git(cwd, ['reset', '--hard', 'HEAD']); await git.git(cwd, ['clean', '-fd']); await git.git(cwd, ['switch', 'local/review'])
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await git.git(cwd, ['reset', '--hard', 'HEAD'])
  await page.setViewportSize({ width: 1440, height: 950 })
  await git.git(cwd, ['switch', '--detach', 'local/review'])
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await page.getByRole('button', { name: '커밋 그래프', exact: true }).click()
  await page.getByRole('button', { name: 'HEAD 위치로 이동', exact: true }).getByText('Detached HEAD', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'HEAD 위치로 이동', exact: true }).click()
  await page.locator(`.bl-repository:visible .bl-graph-row[aria-current=true][aria-pressed=true] svg[data-sha="${feature}"]`).waitFor()
  await open('main'); await choose('현재 브랜치와 비교')
  assert.equal(await page.getByRole('combobox', { name: '반영할 브랜치', exact: true }).inputValue(), feature)
  // Identical nested names remain readable in the narrow sidebar without changing HEAD.
  const longBranch = 'feature/결제/payment-reconciliation-with-external-provider-and-ledger-retry'
  await git.git(cwd, ['branch', longBranch, feature])
  await git.git(cwd, ['update-ref', `refs/remotes/origin/${longBranch}`, feature])
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await page.setViewportSize({ width: 760, height: 580 })
  await sidebar.getByLabel('브랜치·Stash·Worktree 찾기').fill('payment-reconciliation')
  for (const name of [longBranch, `origin/${longBranch}`]) {
    const row = branch(name)
    await row.hover({ position: { x: 12, y: 12 } })
    await tooltip.getByText(name, { exact: true }).waitFor()
    assert.ok(await tooltip.evaluate(el => el.getBoundingClientRect().right <= innerWidth && el.scrollWidth <= el.clientWidth))
    if (process.env.BRANCHLINE_SCREENSHOTS && name.startsWith('origin/')) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'sidebar-branch-tooltip.png') })
    await page.keyboard.press('Escape')
    await tooltip.waitFor({ state: 'hidden' })
  }
  const remoteRow = branch(`origin/${longBranch}`)
  // Long names are ellipsized (full name in the tooltip) so the row menu stays reachable without sideways scrolling.
  assert.ok(await remoteRow.evaluate(row => {
    const scroll = row.closest('.bl-sidebar-scroll'), label = row.querySelector('.bl-repo-tree-label > span')
    const actions = row.closest('.bl-tree-branch-actions')?.querySelector('[aria-haspopup=menu]')
    const right = scroll.getBoundingClientRect().right, menuBox = actions?.getBoundingClientRect()
    return label.scrollWidth > label.clientWidth && getComputedStyle(label).textOverflow === 'ellipsis' && scroll.scrollWidth <= scroll.clientWidth + 1 && !!menuBox && menuBox.right <= right + 1 && document.documentElement.scrollWidth <= innerWidth
  }), 'Long branch names are ellipsized and their menu button stays visible')
  await page.mouse.move(740, 570)
  await remoteRow.focus()
  await tooltip.getByText(`origin/${longBranch}`, { exact: true }).waitFor()
  await page.keyboard.press('Shift+F10'); await menu.waitFor()
  await tooltip.waitFor({ state: 'hidden' })
  await page.keyboard.press('Escape'); await menu.waitFor({ state: 'hidden' })
  await page.waitForFunction(name => document.activeElement?.getAttribute('aria-label') === name, `이력 조회: origin/${longBranch}`)
  assert.equal((await git.state(cwd)).head, feature)
  await page.getByRole('button', { name: 'branch-menu-project 탭 닫기', exact: true }).click()
  console.log('PASS: branch location beyond 100 commits vs explicit Solo, right-click/keyboard/visible menu, ref badges, copy, comparison, create/rename/safe-delete/tracking checkout, shared dialogs and responsive accessibility')
}
