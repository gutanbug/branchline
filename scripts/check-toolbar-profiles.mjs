import assert from 'node:assert/strict'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import path from 'node:path'
import git from '../electron/git.cjs'

export async function checkToolbarProfiles(app, page, root, accessibility) {
  const cwd = path.join(root, 'toolbar-profile'), remote = path.join(root, 'toolbar-remote.git')
  await mkdir(cwd); await git.git(cwd, ['init', '-b', 'feature/긴-프로젝트-브랜치-호버-검증'])
  await git.git(cwd, ['config', 'user.name', 'Initial Author']); await git.git(cwd, ['config', 'user.email', 'initial@example.invalid']); await git.git(cwd, ['config', 'commit.gpgsign', 'false'])
  await writeFile(path.join(cwd, 'base.txt'), 'base\n'); await git.git(cwd, ['add', '.']); await git.git(cwd, ['commit', '-m', 'toolbar base'])
  await git.git(root, ['init', '--bare', remote]); await git.git(cwd, ['remote', 'add', 'origin', remote])
  await app.evaluate(({ dialog }, cwd) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [cwd] }) }, cwd)
  await page.getByRole('button', { name: '저장소 열기', exact: true }).first().click()
  await page.getByRole('button', { name: /^toolbar-profile feature\// }).waitFor()
  const toolbar = page.getByRole('group', { name: 'Git 빠른 작업' })
  await toolbar.getByRole('button', { name: '원격 이력 가져오기', exact: true }).waitFor()
  assert.equal(await toolbar.getByRole('button').count(), 6)
  assert.equal(await page.getByRole('button', { name: '작성자 설정', exact: true }).count(), 0)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('button', { name: '앱 설정', exact: true }).click()
  await page.getByLabel('프로필 이름', { exact: true }).fill('업무 프로필')
  await page.getByLabel('작성자 이름', { exact: true }).fill('한글 개발자')
  await page.getByLabel('작성자 이메일', { exact: true }).fill('developer@example.invalid')
  const composing = await page.getByLabel('작성자 이름', { exact: true }).evaluate(element => {
    const event = new KeyboardEvent('keydown', { key: 'Enter', isComposing: true, bubbles: true, cancelable: true }); element.dispatchEvent(event); return event.defaultPrevented
  }); assert.equal(composing, true)
  await page.getByRole('button', { name: '프로필 저장', exact: true }).click()
  await page.getByText('프로필을 저장했습니다. 아래에서 적용할 저장소를 선택하세요.', { exact: true }).waitFor()
  await page.getByRole('button', { name: '선택한 저장소에 적용', exact: true }).click()
  await page.getByText('toolbar-profile 작성자를 업무 프로필로 변경했습니다.', { exact: true }).waitFor()
  assert.deepEqual((await git.state(cwd)).identity, { name: '한글 개발자', email: 'developer@example.invalid' })
  const profileFile = await app.evaluate(({ app }) => `${app.getPath('userData')}/workspace.json`)
  const profiles = JSON.parse(await readFile(profileFile, 'utf8')).profiles
  assert.equal(profiles[0].label, '업무 프로필')
  const invalid = await page.evaluate(async () => { try { await window.branchline.saveProfiles([{ id: crypto.randomUUID(), label: 'bad', name: 'bad\nname', email: 'not-email' }]); return false } catch { return true } })
  assert.equal(invalid, true)
  await page.getByRole('button', { name: '새 프로필', exact: true }).click()
  await page.getByLabel('프로필 이름', { exact: true }).fill('개인')
  await page.getByLabel('작성자 이름', { exact: true }).fill('개인 개발자')
  await page.getByLabel('작성자 이메일', { exact: true }).fill('personal@example.invalid')
  await page.getByRole('button', { name: '프로필 저장', exact: true }).click()
  await page.getByText('프로필을 저장했습니다. 아래에서 적용할 저장소를 선택하세요.', { exact: true }).waitFor()
  await page.getByRole('combobox', { name: '적용할 프로필', exact: true }).selectOption(profiles[0].id)
  await page.getByRole('combobox', { name: '편집할 프로필', exact: true }).selectOption(profiles[0].id)
  assert.equal(await page.getByLabel('작성자 이름', { exact: true }).inputValue(), '한글 개발자')
  await page.locator('main').evaluate(element => { element.scrollTop = 0 })
  await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'author-profiles.png') })
  await page.getByRole('button', { name: /^toolbar-profile feature\// }).click()
  await toolbar.getByRole('button', { name: '현재 커밋 게시', exact: true }).click()
  await page.getByRole('dialog', { name: 'Push', exact: true }).getByRole('button', { name: 'Push', exact: true }).click()
  await page.getByRole('dialog', { name: 'Push', exact: true }).waitFor({ state: 'hidden' })
  assert.equal((await git.git(remote, ['rev-parse', 'refs/heads/feature/긴-프로젝트-브랜치-호버-검증'])).trim(), (await git.state(cwd)).head)
  await toolbar.getByRole('button', { name: '원격 이력 가져오기', exact: true }).click()
  await page.getByRole('dialog', { name: 'Fetch', exact: true }).getByRole('button', { name: 'Fetch', exact: true }).click()
  await page.getByRole('dialog', { name: 'Fetch', exact: true }).waitFor({ state: 'hidden' })
  await toolbar.getByRole('button', { name: '원격 변경 반영 · fast-forward', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Pull · fast-forward', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await toolbar.getByRole('button', { name: '브랜치 만들기', exact: true }).click()
  await page.getByRole('dialog').getByLabel('새 브랜치 이름').fill('feature/from-toolbar')
  await page.getByRole('dialog').getByRole('button', { name: '저장', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.ok((await git.state(cwd)).refs.some(ref => ref.name === 'feature/from-toolbar'))
  await writeFile(path.join(cwd, 'base.txt'), 'stash from toolbar\n')
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await toolbar.getByRole('button', { name: 'Stash 변경 보관', exact: true }).click()
  await page.getByRole('dialog').getByLabel('보관 메시지').fill('toolbar stash')
  await page.getByRole('dialog').getByRole('button', { name: '변경 보관', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await toolbar.getByRole('button', { name: '최근 Stash 복원 후 제거', exact: true }).click()
  await page.getByRole('dialog', { name: 'Pop', exact: true }).getByRole('button', { name: 'Pop', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await readFile(path.join(cwd, 'base.txt'), 'utf8'), 'stash from toolbar\n')
  assert.equal((await git.git(cwd, ['stash', 'list'])).trim(), '')
  await page.getByRole('button', { name: 'Git 작업 알림 닫기', exact: true }).click()
  for (const size of [{ width: 1440, height: 950 }, { width: 760, height: 580 }]) {
    await page.setViewportSize(size)
    const tab = page.getByRole('button', { name: /^toolbar-profile feature\// })
    const before = await tab.boundingBox(); await tab.hover(); const after = await tab.boundingBox()
    assert.deepEqual(after, before, 'Project hover preserves dimensions and text layout')
    for (const button of await toolbar.getByRole('button').all()) { const bounds = await button.boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= size.width && bounds.height >= 44) }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await accessibility(page)
    if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, `toolbar-hover-${size.width}.png`) })
  }
  await page.getByRole('button', { name: 'toolbar-profile 탭 닫기', exact: true }).click()
  console.log('PASS: central Git toolbar real local push/fetch/pull/branch/stash/pop, saved author profiles, IPC validation, IME, per-repository identity, tab hover stability, keyboard targets, narrow layout and accessibility')
}
