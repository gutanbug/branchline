import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import git from '../electron/git.cjs'
import { checkAgentChat } from './check-agent-chat.mjs'

export async function checkConflicts(app, page, root, accessibility) {
  const cwd = path.join(root, 'conflict-fixture'), file = '한글 file.txt'
  await mkdir(cwd); await git.git(cwd, ['init', '-b', 'main'])
  await git.git(cwd, ['config', 'user.name', 'Fixture']); await git.git(cwd, ['config', 'user.email', 'test@example.invalid']); await git.git(cwd, ['config', 'commit.gpgsign', 'false'])
  for (const [branch, value] of [['', 'base'], ['topic', 'topic'], ['main', 'main']]) {
    if (branch) await git.git(cwd, branch === 'topic' ? ['checkout', '-b', branch] : ['checkout', branch])
    await writeFile(path.join(cwd, file), `${value}\n`); await git.git(cwd, ['add', '.']); await git.git(cwd, ['commit', '-m', value])
  }
  await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }) }, cwd)
  await page.getByRole('button', { name: '저장소 열기', exact: true }).first().click()
  await page.getByRole('button', { name: 'conflict-fixture 탭 닫기', exact: true }).waitFor()
  await page.getByRole('heading', { name: '커밋 그래프', exact: true }).waitFor()
  await assert.rejects(git.git(cwd, ['merge', 'topic']))
  await page.getByRole('heading', { name: '충돌 해결', exact: true }).waitFor({ timeout: 12000 })
  const editor = page.getByLabel('해결 결과 편집', { exact: true })
  await editor.waitFor(); const original = await editor.inputValue()
  assert.match(original, /<<<<<<< HEAD/)
  await page.getByLabel('Agent에게 전달할 요청', { exact: true }).waitFor()
  await page.getByRole('button', { name: '커밋 그래프', exact: true }).click()
  await writeFile(path.join(cwd, file), original + '\n')
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await page.getByRole('heading', { name: '커밋 그래프', exact: true }).waitFor()
  await page.getByRole('button', { name: '충돌 해결', exact: true }).click()
  assert.equal(await editor.inputValue(), original, 'External edits must not overwrite a loaded conflict editor')
  await writeFile(path.join(cwd, file), original)
  await checkAgentChat(app, page, root, cwd, file, accessibility)
  await accessibility(page)
  await editor.fill('한글 병합 결과\n')
  await editor.dispatchEvent('compositionstart', { data: '가' })
  await editor.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true, bubbles: true })
  assert.equal(await page.getByRole('dialog').count(), 0)
  assert.equal(await readFile(path.join(cwd, file), 'utf8'), original)
  await editor.dispatchEvent('compositionend', { data: '가' })
  await page.getByRole('button', { name: '내 변경 사항 1', exact: true }).click()
  await page.getByRole('button', { name: '충돌 해결', exact: true }).click()
  assert.equal(await editor.inputValue(), '한글 병합 결과\n')
  await page.getByRole('button', { name: '원본 불러오기', exact: true }).click()
  await page.getByRole('dialog', { name: '편집을 버리고 다시 불러오기' }).waitFor()
  await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await editor.inputValue(), '한글 병합 결과\n')
  await page.setViewportSize({ width: 1440, height: 950 })
  if (process.env.BRANCHLINE_SCREENSHOTS) {
    await page.getByRole('heading', { name: '충돌 해결', exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'desktop-conflicts.png'), fullPage: true })
  }
  await page.setViewportSize({ width: 760, height: 580 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await accessibility(page)
  await page.getByRole('button', { name: '결과 검토 후 저장', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '해결 결과 검토' })
  await modal.waitFor(); await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'desktop-conflicts-narrow.png'), fullPage: true })
  await writeFile(path.join(cwd, file), 'external edit\n')
  await modal.getByRole('button', { name: '작업 파일에 저장', exact: true }).click()
  await modal.getByRole('alert').filter({ hasText: '바뀌었습니다' }).waitFor()
  assert.equal(await readFile(path.join(cwd, file), 'utf8'), 'external edit\n')
  await modal.getByRole('button', { name: '취소', exact: true }).click()
  await page.getByRole('button', { name: '원본 불러오기', exact: true }).click()
  await page.getByRole('button', { name: '편집 버리고 불러오기', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await editor.inputValue(), 'external edit\n')
  await editor.fill('resolved\n')
  await page.getByRole('button', { name: '결과 검토 후 저장', exact: true }).click()
  await page.getByRole('button', { name: '작업 파일에 저장', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await readFile(path.join(cwd, file), 'utf8'), 'resolved\n')
  assert.equal((await git.state(cwd)).files[0].conflict, true)
  await page.getByRole('button', { name: '직전 저장 복원', exact: true }).click()
  await page.getByRole('button', { name: '원본 복원', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await editor.inputValue(), 'external edit\n')
  await page.getByRole('button', { name: '해결 표시', exact: true }).click()
  await page.getByRole('button', { name: '스테이징하고 해결 표시', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.locator('.bl-conflicts:visible').getByText('미해결 충돌이 없습니다', { exact: true }).waitFor()
  assert.equal((await git.state(cwd)).operation, 'merge')
  assert.equal(await git.git(cwd, ['show', `:${file}`]), 'external edit\n')
  await page.getByRole('button', { name: 'merge 계속', exact: true }).click()
  await page.getByRole('dialog', { name: 'merge 계속', exact: true }).waitFor()
  await accessibility(page)
  await writeFile(path.join(cwd, 'external-after-review.txt'), 'external change\n')
  await page.getByRole('dialog').getByRole('button', { name: 'merge 계속', exact: true }).click()
  await page.getByRole('dialog').getByRole('alert').filter({ hasText: '상태가 바뀌었습니다' }).waitFor()
  assert.equal((await git.state(cwd)).operation, 'merge')
  await page.getByRole('dialog').getByRole('button', { name: '취소', exact: true }).click()
  await page.getByRole('button', { name: 'merge 계속', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'merge 계속', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal((await git.state(cwd)).operation, null)
  assert.equal((await git.history(cwd)).commits[0].parents.length, 2)
  await page.getByRole('button', { name: '커밋 그래프', exact: true }).click()
  await git.git(cwd, ['switch', '-c', 'next-conflict', 'HEAD^1'])
  await assert.rejects(git.git(cwd, ['merge', 'topic']))
  await page.getByRole('heading', { name: '충돌 해결', exact: true }).waitFor({ timeout: 12000 })
  await editor.waitFor()
  assert.match(await editor.inputValue(), /<<<<<<< HEAD/)
  await editor.fill('새 충돌의 보존할 초안\n')
  await git.git(cwd, ['merge', '--abort'])
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await page.locator('.bl-conflicts:visible').getByText('미해결 충돌이 없습니다', { exact: true }).waitFor()
  await page.getByRole('button', { name: '커밋 그래프', exact: true }).click()
  await assert.rejects(git.git(cwd, ['merge', 'topic']))
  await page.getByRole('heading', { name: '충돌 해결', exact: true }).waitFor({ timeout: 12000 })
  assert.equal(await editor.inputValue(), '새 충돌의 보존할 초안\n')
  await page.getByRole('button', { name: 'conflict-fixture 탭 닫기', exact: true }).click()
  await page.getByRole('button', { name: '편집 버리고 탭 닫기', exact: true }).click()
  console.log('PASS: external merge auto-entry, repeat episode detection and dirty-draft preservation, real conflict IPC, three-way read, IME, draft navigation, preview, stale-write rejection, backup restore, resolve then explicit merge completion, minimum window and accessibility')
}
