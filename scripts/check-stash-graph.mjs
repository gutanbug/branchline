import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import git from '../electron/git.cjs'

export async function checkStashGraph(app, page, root, accessibility) {
  const cwd = path.join(root, 'stash-graph')
  await mkdir(cwd)
  await git.git(cwd, ['init', '-b', 'main'])
  for (const [name, value] of [['user.name', 'Stash Test'], ['user.email', 'stash@example.invalid'], ['commit.gpgsign', 'false']]) await git.git(cwd, ['config', name, value])
  const oldDate = { env: { ...process.env, GIT_AUTHOR_DATE: '2025-01-01T00:00:00Z', GIT_COMMITTER_DATE: '2025-01-01T00:00:00Z' } }
  await writeFile(path.join(cwd, '작업.txt'), 'base\n')
  await git.git(cwd, ['add', '.']); await git.git(cwd, ['commit', '-m', 'Stash 기준 커밋'], oldDate)
  const base = (await git.state(cwd)).head
  await writeFile(path.join(cwd, '작업.txt'), 'base\n보관한 수정\n')
  await writeFile(path.join(cwd, '새 파일.txt'), '미추적 보관 내용\n')
  await git.git(cwd, ['stash', 'push', '-u', '-m', '오래된 한글 Stash'], oldDate)
  const stash = (await git.git(cwd, ['rev-parse', 'stash@{0}'])).trim()
  const tree = (await git.git(cwd, ['rev-parse', 'HEAD^{tree}'])).trim()
  let head = base
  for (let i = 0; i < 130; i++) head = (await git.git(cwd, ['commit-tree', tree, '-p', head, '-m', `이후 작업 ${i}`])).trim()
  await git.git(cwd, ['update-ref', 'refs/heads/main', head])
  await writeFile(path.join(cwd, '작업.txt'), '최신 Stash 내용\n')
  await git.git(cwd, ['stash', 'push', '-m', '최신 Stash'])
  const before = await git.state(cwd)
  const first = await git.history(cwd, { stashSha: stash })
  assert.equal(first.commits.length, 100)
  assert.equal(first.commits.some(commit => commit.sha === stash), false, 'Fixture places the old Stash beyond the first page')
  const next = await git.history(cwd, { stashSha: stash, revisions: first.revisions, offset: 100 })
  assert.ok(next.commits.some(commit => commit.sha === stash && commit.parents[0] === base))
  await assert.rejects(git.history(cwd, { stashSha: '--all' }), /Stash SHA/)
  await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }) }, cwd)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('button', { name: '저장소 열기', exact: true }).first().click()
  const sidebar = page.getByRole('region', { name: '현재 저장소 탐색' })
  const graph = page.locator('.bl-commit-graph:visible')
  await graph.locator('.bl-graph-row').first().waitFor()
  assert.equal(await graph.locator('.bl-graph-row').count(), 100)
  await page.locator('.bl-repository:visible').getByText('커밋 검색·필터', { exact: true }).click()
  await page.locator('.bl-repository:visible').getByLabel('커밋 메시지 검색', { exact: true }).fill('no matching commit')
  await page.getByText('일치하는 커밋이 없습니다', { exact: true }).waitFor()
  const item = sidebar.getByRole('button', { name: /Stash 보기:.*오래된 한글 Stash/ })
  await item.focus(); await page.keyboard.press('Enter')
  const inspector = page.getByRole('complementary', { name: 'Stash 상세', exact: true })
  await inspector.getByRole('button', { name: '작업.txt 변경 열기' }).click()
  await page.getByRole('tabpanel', { name: '작업.txt', exact: true }).getByText('보관한 수정', { exact: true }).waitFor()
  await inspector.getByRole('button', { name: '새 파일.txt 변경 열기' }).click()
  await page.getByRole('tabpanel', { name: '새 파일.txt', exact: true }).getByText('미추적 보관 내용', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await inspector.getByText('커밋 정보', { exact: true }).click()
  assert.ok((await inspector.innerText()).includes('2 files changed'))
  assert.ok((await inspector.innerText()).includes('새 파일.txt'), 'Korean paths remain readable')
  assert.equal(await page.locator('.bl-repository:visible').getByLabel('커밋 메시지 검색', { exact: true }).inputValue(), '')
  const selected = graph.locator('.bl-graph-row[aria-pressed=true]')
  async function revealed() {
    await page.waitForFunction(sha => {
      const row = document.querySelector(`.bl-commit-graph .bl-graph-row[aria-pressed=true] svg[data-sha="${sha}"]`)?.closest('button')
      const list = row?.closest('.bl-commit-graph')
      if (!row || !list) return false
      const r = row.getBoundingClientRect(), b = list.getBoundingClientRect()
      return r.top >= b.top && r.bottom <= b.bottom
    }, stash)
  }
  await revealed()
  assert.ok(await graph.locator('.bl-graph-row').count() > 100)
  assert.equal(await selected.locator(`[data-parent="${base}"]`).count(), 1, 'Stash is connected to its actual base')
  await page.locator('.bl-repository:visible').getByText('커밋 검색·필터', { exact: true }).click()
  await accessibility(page)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'stash-graph.png') })
  await graph.evaluate(element => { element.scrollTop = 0 })
  await item.click(); await revealed()
  // Removing a newer Stash changes stash@{n}; the selected SHA and diff must remain correct.
  await git.git(cwd, ['stash', 'drop', 'stash@{0}'])
  await page.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await item.click(); await revealed()
  await inspector.getByRole('button', { name: '새 파일.txt 변경 열기' }).click()
  await page.getByRole('tabpanel', { name: '새 파일.txt', exact: true }).getByText('미추적 보관 내용', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 760, height: 580 })
  await item.click(); await revealed(); await accessibility(page)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight), true)
  if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, 'stash-graph-narrow.png') })
  await selected.click()
  await inspector.waitFor({ state: 'hidden' })
  await item.click(); await revealed()
  await graph.getByRole('button', { name: /^Stash 기준 커밋/ }).click()
  await page.getByRole('complementary', { name: '커밋 상세', exact: true }).getByLabel('변경 파일 목록', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('complementary', { name: '커밋 상세', exact: true }).waitFor({ state: 'hidden' })
  const after = await git.state(cwd)
  assert.equal(after.head, before.head); assert.equal(after.branch, before.branch); assert.deepEqual(after.files, before.files)
  await page.setViewportSize({ width: 1440, height: 950 })
  console.log('PASS: old Stash graph navigation across pages, tracked/untracked diff, filter reset, repeat reveal, stable SHA after renumbering, narrow layout, deselection, read-only browsing')
}
