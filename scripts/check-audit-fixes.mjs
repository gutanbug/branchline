import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import git from '../electron/git.cjs'

export async function checkAuditFixes(app, page, root, accessibility) {
  const cwd = path.join(root, 'audit-fixes')
  await mkdir(cwd); await git.git(cwd, ['init', '-b', 'main'])
  for (const [key, value] of [['user.name', 'Tester'], ['user.email', 'test@example.invalid'], ['commit.gpgsign', 'false']]) await git.git(cwd, ['config', key, value])
  async function commit(value) { await writeFile(path.join(cwd, '한글.txt'), `${value}\n`); await git.git(cwd, ['add', '.']); await git.git(cwd, ['commit', '-m', value]) }
  await commit('base'); await git.git(cwd, ['switch', '-c', 'topic']); await commit('topic'); await git.git(cwd, ['switch', 'main']); await commit('main')
  const head = (await git.state(cwd)).head
  await app.evaluate(({ dialog }, cwd) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [cwd] }) }, cwd)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('button', { name: '저장소 열기', exact: true }).first().click()
  await page.getByRole('button', { name: /^audit-fixes main/ }).waitFor()
  await page.locator('.bl-repository:visible .bl-graph-row').first().waitFor()
  const workspace = page.locator('.bl-repository:visible')
  await workspace.locator('.bl-graph-row').first().click()
  await workspace.getByRole('button', { name: '커밋 상세 크게 보기', exact: true }).click()
  await page.getByRole('dialog', { name: '커밋 상세 크게 보기', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await workspace.getByRole('complementary', { name: '커밋 상세', exact: true }).isVisible(), true)
  await workspace.getByRole('button', { name: '커밋 상세 닫기', exact: true }).click()
  await workspace.getByText('커밋 검색·필터', { exact: true }).click()
  await workspace.getByLabel('커밋 메시지 검색').fill('absent-message')
  const empty = page.getByText('일치하는 커밋이 없습니다', { exact: true }); await empty.waitFor()
  for (const size of [{ width: 1440, height: 950 }, { width: 760, height: 580 }]) {
    await page.setViewportSize(size)
    assert.equal(await empty.evaluate(element => { const box = element.getBoundingClientRect(); return element.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2)) }), true, 'Open filters do not cover empty feedback')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    if (process.env.BRANCHLINE_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.BRANCHLINE_SCREENSHOTS, `fixed-filter-${size.width}.png`) })
  }
  await page.setViewportSize({ width: 1440, height: 950 })
  await workspace.getByRole('button', { name: '브랜치 비교', exact: true }).click()
  await workspace.getByRole('combobox', { name: '가져올 브랜치', exact: true }).selectOption('refs/heads/topic')
  await workspace.getByRole('combobox', { name: '반영할 브랜치', exact: true }).selectOption('refs/heads/main')
  await workspace.getByRole('region', { name: '가져올 브랜치 그래프', exact: true }).getByText('이쪽에만 1개', { exact: true }).waitFor()
  for (const [button, title, submit] of [['topic → main Merge', 'Merge 검토', 'Merge 실행'], ['현재 브랜치를 topic 위로 Rebase', 'Rebase 검토', 'Rebase 실행']]) {
    await workspace.getByRole('button', { name: button, exact: true }).click()
    const review = page.getByRole('dialog', { name: title, exact: true })
    await review.getByRole('button', { name: submit, exact: true }).click(); await review.waitFor({ state: 'hidden' })
    await workspace.getByRole('heading', { name: '충돌 해결', exact: true }).waitFor()
    await workspace.getByLabel('해결 결과 편집', { exact: true }).waitFor()
    assert.ok((await git.state(cwd)).operation)
    await workspace.getByLabel('해결 결과 편집', { exact: true }).fill('미저장 해결안')
    await workspace.getByRole('button', { name: '작업 중단', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '취소', exact: true }).click()
    assert.equal(await workspace.getByLabel('해결 결과 편집', { exact: true }).inputValue(), '미저장 해결안')
    await workspace.getByRole('button', { name: '작업 중단', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '작업 중단', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.equal((await git.state(cwd)).head, head); assert.equal((await git.state(cwd)).operation, null)
    await workspace.getByRole('button', { name: '브랜치 비교', exact: true }).click()
    await workspace.getByRole('region', { name: '가져올 브랜치 그래프', exact: true }).getByText('이쪽에만 1개', { exact: true }).waitFor()
  }
  await page.getByRole('button', { name: 'Worktree 관리', exact: true }).click()
  await workspace.getByRole('button', { name: 'Worktree 만들기', exact: true }).click()
  await page.getByRole('combobox', { name: 'Worktree 생성 방식', exact: true }).selectOption('existing')
  assert.equal(await page.getByRole('dialog').getByLabel('새 브랜치 이름').count(), 0)
  await page.getByRole('combobox', { name: 'Worktree 브랜치', exact: true }).selectOption('refs/heads/topic')
  const target = path.join(root, 'existing-ui')
  await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, target)
  await page.getByRole('button', { name: '새 폴더 위치 선택', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '저장', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' }); assert.equal((await git.state(target)).branch, 'topic')
  await page.getByRole('button', { name: '앱 설정', exact: true }).click()
  await page.getByRole('button', { name: '새 프로필', exact: true }).click()
  await page.getByRole('button', { name: '프로필 저장', exact: true }).click()
  assert.equal(await page.locator('.bl-profile-settings [aria-invalid=true]').count(), 3)
  assert.equal(await page.getByLabel('프로필 이름', { exact: true }).evaluate(element => document.activeElement === element), true)
  await page.getByLabel('프로필 이름', { exact: true }).fill('보호할 초안')
  await page.getByRole('button', { name: '새 프로필', exact: true }).click()
  await page.getByRole('dialog', { name: '저장하지 않은 프로필' }).getByRole('button', { name: '계속 편집' }).click()
  assert.equal(await page.getByLabel('프로필 이름', { exact: true }).inputValue(), '보호할 초안')
  await page.getByLabel('작성자 이름', { exact: true }).fill('Tester'); await page.getByLabel('작성자 이메일', { exact: true }).fill('tester@example.invalid')
  await page.getByRole('button', { name: '프로필 저장', exact: true }).click()
  await page.getByText('프로필을 저장했습니다. 아래에서 적용할 저장소를 선택하세요.', { exact: true }).waitFor()
  await page.getByRole('button', { name: '프로필 삭제', exact: true }).click()
  await page.getByRole('dialog', { name: '프로필 삭제 확인' }).getByRole('button', { name: '계속 편집' }).click()
  assert.equal(await page.getByLabel('프로필 이름', { exact: true }).inputValue(), '보호할 초안')
  await page.getByRole('button', { name: '프로필 삭제', exact: true }).click()
  await page.getByRole('dialog', { name: '프로필 삭제 확인' }).getByRole('button', { name: '프로필 삭제', exact: true }).click()
  await page.getByText('프로필을 삭제했습니다. 저장소에 적용된 작성자는 유지됩니다.', { exact: true }).waitFor()
  await accessibility(page)
  const agents = await page.evaluate(() => window.branchline.agents())
  await app.evaluate(({ ipcMain }, agents) => { let count = 0; ipcMain.removeHandler('branchline:agents'); ipcMain.handle('branchline:agents', () => ++count === 1 ? { ok: false, error: '검증용 일시 오류' } : { ok: true, value: agents }) }, agents)
  await page.getByRole('button', { name: 'AI Agents', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: '검증용 일시 오류' }).waitFor()
  await page.getByRole('button', { name: 'Agent 다시 조회', exact: true }).click()
  await page.getByRole('heading', { name: 'Claude Code', exact: true }).waitFor()
  await app.evaluate(({ ipcMain }, agents) => { ipcMain.removeHandler('branchline:agents'); ipcMain.handle('branchline:agents', () => ({ ok: true, value: agents })) }, agents)
  await page.getByRole('button', { name: /^audit-fixes main/ }).click()
  await page.getByRole('button', { name: 'audit-fixes 탭 닫기', exact: true }).click()
  console.log('PASS: visible filter feedback, reviewed Merge/Rebase to conflict/abort, existing-branch Worktree, profile validation, draft preservation and confirmed deletion')
}
