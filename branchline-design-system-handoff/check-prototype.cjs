const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync(__dirname + '/branchline.html','utf8');
const scripts=[...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
for (const script of scripts) new vm.Script(script);
assert.equal(scripts.length,2);
assert.ok(!/\[REPLACE\]|\{\{/.test(html));
vm.runInNewContext(scripts[0]+`
let p=compareRefs(source,target);
assert.deepEqual([p.source.length,p.target.length,p.common.length],[5,2,4]);
assert.equal(filterRows(p.all,'키보드').length,2);
assert.equal(filterRows(p.all,'','김민서','2026-09-10').length,3);
assert.equal(filterRows(p.all,'없는검색어').length,0);
assert.ok(!reachable(refs['feature/branch-filter']).has('m1'));
assert.deepEqual(visibleParents('f1',new Set(['f1','c1'])),[{id:'c1',hidden:true}]);
assert.deepEqual(visibleParents('f1',new Set(['f1','f2'])),[{id:'f2',hidden:false}]);
assert.throws(()=>pickCommits(['m1'],source,target));
assert.throws(()=>pickCommits(['f2'],source,target));
assert.throws(()=>pickCommits(['f1'],source,source));
assert.equal(pickCommits(['f1','f4'],source,target),2);
assert.equal(commits[0].origin,'f1');
assert.equal(commits[1].origin,'f4');
assert.equal(commits[0].parents[0],commits[1].id);
assert.equal(refs.main,commits[0].id);
assert.equal(refs[source],'f1');
assert.throws(()=>pickCommits(['f1'],source,target));
assert.ok(reachable(refs.main).has('m1'));
`,{assert,structuredClone});
console.log('통과: 스크립트 구문, 브랜치 차집합, 필터, 숨겨진 부모 연결, 체리픽 검증·순서·원본 보존');
